const compact = (text: string) => text.toLowerCase().replace(/\s+/g, '');

/** A bot reply: one short message plus tappable next steps (LINE quick replies). */
export type BotReply = { text: string; quickReplies: string[] };

const categoryButtons = () => CATEGORIES.map((c) => c.label);

function mainMenu(text = 'อยากรู้เรื่องไหนคะ? เลือกหมวดด้านล่าง หรือพิมพ์คำถามสั้น ๆ ได้เลย เช่น "เชื่อมกลุ่ม" "เช็คชื่อ"'): BotReply {
  return { text, quickReplies: categoryButtons() };
}

function categoryMenu(id: CategoryId): BotReply {
  const category = CATEGORIES.find((c) => c.id === id)!;
  return {
    text: `${category.intro} แตะที่ปุ่มด้านล่างได้เลย 👇`,
    quickReplies: [...FAQ.filter((e) => e.category === id).map((e) => e.label), MAIN_MENU_LABEL],
  };
}

function answer(entry: FaqEntry): BotReply {
  // Next steps: the other questions of the same group, then back to the menu.
  const related = FAQ.filter((e) => e.category === entry.category && e !== entry).map((e) => e.label);
  return { text: entry.answer, quickReplies: [...related, MAIN_MENU_LABEL] };
}

